// Состояние игры (базовые переменные)
int hp = 100;
int resources = 50; // Евродоллары
int score = 0; // Очки репутации (Street cred)
int turn = 1;
void printHUD() {
 std::cout << "\n================ [ХОД: " << turn << " | STREET CRED: " << score
<< "] ================\n";
 std::cout << "♥︎ Биомонитор (hp): " << hp << "/100 | ◼ Чип валюты: " <<
resources << "\n";
 std::cout << "--------------------------------------------------------
\n";
}
