#include <iostream>
#include <string>
#include <cstdlib>
#include <ctime>
// Состояние игры (базовые переменные)
int hp = 100;
int resources = 50; // Евродоллары
int score = 0; // Очки репутации (Street cred)
int turn = 1;
void printHUD() {
 std::cout << "\n================ [ХОД: " << turn << " | STREET CRED: " << score<< "] ================\n";
 std::cout << "♥︎ Биомонитор (hp): " << hp << "/100 | ◼ Чип валюты: " <<resources << "\n";
 std::cout << "--------------------------------------------------------\n";
}

// Разработчик 1: Функция риска (Issue #1) — Заказ от фиксера (Контракт)
void takeFixerJob() {
    std::cout << "\n Вакадо или Рехина присылают вам опасный заказ: налет на конвой «Арасаки»...\n";

    // Шанс ~50% (через rand() % 2)
    if (rand() % 2 == 0) {
        int lootEddies = 100 + rand() % 201; // +100-300 эдди
        int bonusCred = 200 + rand() % 301;  // +200-500 Street Cred
        resources += lootEddies;
        score += bonusCred;
        std::cout << "УСПЕХ! Вы взломали терминал конвоя. Получено +" << lootEddies << " €$ и +" << bonusCred << " к репутации!\n";
    } else {
        int damage = 30 + rand() % 21; // 30-50 урона
        hp -= damage;
        std::cout << "ЗАСАДА! Элитные штурмовики «Макс-Так» зажали вас в переулке. Получено " << damage << " ед. урона.\n";
    }
}

// Разработчик 2: Модуль отхила и экономики (Issue #2) — Визит к Риперу
void visitRipperdoc() {
    std::cout << "\n Вы заходите в клинику к Виктору Вектору. Доступные медицинские услуги:\n";
    std::cout << "1. Установить боевой стимулятор «МаксДок» (+40 HP) — Стоимость: 40 €$\n";
    std::cout << "2. Просто обновить прошивку кибердеки (Бесплатно, без эффекта)\n";
    std::cout << "Выберите действие > ";

    int subChoice;
    std::cin >> subChoice;

    if (subChoice == 1) {
        if (resources < 40) {
            std::cout << " Ошибка транзакции: Недостаточно евродолларов на чипе! Вик разводит руками.\n";
        } else if (hp >= 100) {
            std::cout << " Биомонитор в норме. Ставить стимулятор нет необходимости!\n";
        } else {
            resources -= 40;
            hp += 40;
            if (hp > 100) hp = 100; // Логическая защита: здоровье не выше 100!
            std::cout << " Хром послушно зажужжал. «МаксДок» впрыснул лекарство. Здоровье восстановлено!\n";
        }
    } else {
        std::cout << "Вы поболтали с Виком о заговорах корпораций и ушли.\n";
    }
}

// Разработчик 3: Модуль рулетки/событий (Issue #3) — Взлом Сети (Netrunning)
void netrunHack() {
    std::cout << "\n[⚡] Вы подключаетесь к защищенной подсети «Милитех» через точку доступа...\n";
    std::cout << "Запустить демоны взлома? (1 - Начать взлом, 0 - Отключиться от греха подальше): ";

    int agree;
    std::cin >> agree;
    if (agree != 1) {
        std::cout << "Вы выдергиваете кабель из порта затылка.\n";
        return;
    }

    // Имитация броска кубика D20 / взлома матрицы
    int MatrixResult = 1 + rand() % 20;
    std::cout << "Индикатор взлома показывает индекс уязвимости: " << MatrixResult << "\n";

    if (MatrixResult == 20) {
        std::cout << "ДЖЕКПОТ! Вы нашли скрытый корпоративный архив. Ваш Street Cred удваивается!\n";
        score *= 2;
    } else if (MatrixResult >= 11) {
        std::cout << "Удачный взлом. Удалось выкачать немного данных и репутации (+150 к очкам).\n";
        score += 150;
    } else if (MatrixResult >= 3) {
        std::cout << "⚠︎ Корпоративный лед (ICE) заблокировал часть данных. Репутация немного просела (-50 очков).\n";
        score -= 50;
        if (score < 0) score = 0;
    } else {
        std::cout << "КРИТИЧЕСКАЯ УЯЗВИМОСТЬ! Сетевой демон «Киберпсихоз» ударил током по вашей нервной системе! HP падает до 1.\n";
        hp = 1;
    }
}

int main() {
 srand(time(NULL));
 int choice = 0;
 std::cout << ">>> ЗАПУСК СИМУЛЯЦИИ: ДОБРО ПОЖАЛОВАТЬ В НАЙТ-СИТИ (CYBERPUNK 2077) <<<\n";
 while (hp > 0) {
 printHUD();
 std::cout << "1. Заказ от фиксера (Контракт / Риск)\n";
 std::cout << "2. Клиника Рипера (Установка хрома и МаксДок)\n";
 std::cout << "3. Точка доступа Сети (Взлом и Нетраннинг)\n";
 std::cout << "0. Уехать из города и зафиксировать репутацию\n";
 std::cout << "Выберите действие > ";
 if (!(std::cin >> choice)) break;

 switch (choice) {
 case 1:
takeFixerJob();
break;
 case 2:
 visitRipperdoc();
 break;
 case 3:
netrunHack();
 break;
 case 0:
 hp = 0;
 break;
 default:
 std::cout << "\nНеизвестная команда на чипе!\n";
 break;
 }
 // Каждый успешный ход дает очки Street Cred
 if (hp > 0) {
 turn++;
 score += 10;
 }
 }
 std::cout << "\n СИМУЛЯЦИЯ ОКОНЧЕНА. Вы стали легендой Найт-Сити с рекордом: " << score << " Street Cred!\n";
 return 0;
}
